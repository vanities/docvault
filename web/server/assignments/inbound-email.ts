// Picks up owner replies to assignment emails and turns them into thread messages.
//
// Outbound assignment emails set Reply-To to a per-assignment address on a Resend receiving
// domain (reply-address.ts). Resend stores whatever arrives there, and this poller reads it back
// over the same API key the sender uses — polling, not webhooks, because the server is not
// reachable from the internet. A matched reply is appended as an owner message (via: 'email') and
// triggers a reply run, which emails its answer back.
//
// What gets through: the address token must match the assignment (the secret only that
// assignment's emails carry), the sender must be the configured owner, auto-generated mail
// (out-of-office loops) is dropped, and an email whose SPF, DKIM and DMARC all hard-fail is
// dropped. Every email is processed once; the ids it has seen live in
// DATA_DIR/.docvault-inbound-email.json, server-owned like the other assignment files.
import path from 'node:path';
import { promises as fs } from 'node:fs';
import { DATA_DIR, getAssignmentsReplyDomain, getEmailConfig } from '../data.js';
import { firstRecipient } from '../alerts.js';
import { createLogger } from '../logger.js';
import { createWriteLock, writeJsonAtomic } from '../write-lock.js';
import { requestRun } from './runner.js';
import { extractAddress, parseReplyLocalPart, stripQuotedReply } from './reply-address.js';
import { appendEntries, loadIndex, newId } from './store.js';
import type { Assignment, RunTrigger } from './types.js';

const log = createLogger('Assignments');

const TICK_MS = 60_000;
const LIST_URL = 'https://api.resend.com/emails/receiving?limit=20';
const RECEIVING_URL = 'https://api.resend.com/emails/receiving';
/** Same cap as a message posted through the UI (routes/assignments.ts). */
const MAX_MESSAGE = 8000;
/** New emails handled per tick; with the seen ledger this bounds any mail loop's burn rate. */
const MAX_PER_TICK = 10;
const SEEN_MAX = 300;

export const INBOUND_STATE_FILE = '.docvault-inbound-email.json';

export interface InboundDeps {
  dataDir: string;
  now: () => Date;
  fetchFn: typeof fetch;
  apiKey: () => Promise<string | null>;
  replyDomain: () => Promise<string | null>;
  /** The owner's address; the only sender whose replies are accepted. */
  recipient: () => Promise<string | null>;
  requestRun: (id: string, trigger: RunTrigger) => Promise<unknown>;
}

export function defaultInboundDeps(): InboundDeps {
  return {
    dataDir: DATA_DIR,
    now: () => new Date(),
    fetchFn: fetch,
    apiKey: async () => (await getEmailConfig()).apiKey || null,
    replyDomain: getAssignmentsReplyDomain,
    recipient: async () => firstRecipient((await getEmailConfig()).toEmail),
    requestRun: (id, trigger) => requestRun(id, trigger),
  };
}

interface InboundState {
  version: 1;
  seen: string[];
}

const withStateLock = createWriteLock();
const statePath = (dataDir: string) => path.join(dataDir, INBOUND_STATE_FILE);

async function readState(dataDir: string): Promise<InboundState> {
  try {
    const raw = JSON.parse(await fs.readFile(statePath(dataDir), 'utf8')) as InboundState;
    return {
      version: 1,
      seen: Array.isArray(raw.seen) ? raw.seen.filter((s) => typeof s === 'string') : [],
    };
  } catch {
    return { version: 1, seen: [] };
  }
}

function markSeen(state: InboundState, id: string, dataDir: string): Promise<void> {
  return withStateLock(async () => {
    state.seen = [...state.seen, id].slice(-SEEN_MAX);
    await writeJsonAtomic(statePath(dataDir), state);
  });
}

// The Resend shapes this poller reads; fields it ignores are left out.
interface ReceivedSummary {
  id: string;
  to?: string[];
  from?: string;
  subject?: string;
}
interface ReceivedEmail extends ReceivedSummary {
  text?: string | null;
  html?: string | null;
  headers?: Record<string, string | string[]> | { name: string; value: string }[];
  authentication?: Record<string, unknown>;
}

/** Header lookup over either shape Resend may use (object map or name/value list). */
export function headerValue(headers: ReceivedEmail['headers'], name: string): string | null {
  if (!headers) return null;
  const want = name.toLowerCase();
  if (Array.isArray(headers)) {
    const hit = headers.find((h) => h?.name?.toLowerCase() === want);
    return hit ? String(hit.value) : null;
  }
  for (const [key, value] of Object.entries(headers)) {
    if (key.toLowerCase() === want) return Array.isArray(value) ? value.join(', ') : String(value);
  }
  return null;
}

/** Out-of-office and other machine mail; a reply to it would only start a mail loop. */
export function isAutoGenerated(headers: ReceivedEmail['headers']): boolean {
  const auto = headerValue(headers, 'auto-submitted');
  if (auto && auto.toLowerCase() !== 'no') return true;
  const precedence = headerValue(headers, 'precedence')?.toLowerCase();
  if (precedence && ['bulk', 'junk', 'auto_reply', 'list'].includes(precedence)) return true;
  return headerValue(headers, 'x-auto-response-suppress') !== null;
}

/** 'pass' / 'fail' out of whatever shape Resend reports a check in, else null. */
function authResult(value: unknown): string | null {
  if (typeof value === 'string') return value.toLowerCase();
  if (value && typeof value === 'object' && 'result' in value) {
    const r = (value as { result?: unknown }).result;
    return typeof r === 'string' ? r.toLowerCase() : null;
  }
  return null;
}

/** True only when every reported check explicitly failed; the token is the primary gate. */
export function authenticationHardFails(
  authentication: Record<string, unknown> | undefined
): boolean {
  if (!authentication) return false;
  const results = ['spf', 'dkim', 'dmarc']
    .map((k) => authResult(authentication[k]))
    .filter((r): r is string => r !== null);
  return results.length > 0 && results.every((r) => r === 'fail');
}

/** The owner's words out of a reply: text (or de-tagged html), quoted history stripped. */
export function replyMessageText(email: Pick<ReceivedEmail, 'text' | 'html'>): string {
  // Plain text is kept verbatim; the html fallback collapses the whitespace de-tagging leaves.
  const raw =
    email.text ??
    (email.html
      ? email.html
          .replace(/<style[\s\S]*?<\/style>/gi, ' ')
          .replace(/<[^>]+>/g, ' ')
          .replace(/[^\S\n]+/g, ' ')
      : '');
  return stripQuotedReply(raw)
    .replace(/\n{3,}/g, '\n\n')
    .trim()
    .slice(0, MAX_MESSAGE);
}

function matchAssignment(
  assignments: Record<string, Assignment>,
  to: string[] | undefined,
  domain: string
): { assignment: Assignment; address: string } | null {
  for (const addr of to ?? []) {
    const clean = extractAddress(addr) ?? addr.trim().toLowerCase();
    const at = clean.lastIndexOf('@');
    if (at < 0 || clean.slice(at + 1) !== domain) continue;
    const parsed = parseReplyLocalPart(clean.slice(0, at));
    if (!parsed) continue;
    const assignment = Object.values(assignments).find(
      (a) => a.id.startsWith(parsed.idPrefix) && a.replyToken === parsed.token
    );
    if (assignment) return { assignment, address: clean };
  }
  return null;
}

let polling = false;

/** One poll; returns how many replies it turned into messages. */
export async function pollInboundEmails(deps: InboundDeps = defaultInboundDeps()): Promise<number> {
  if (polling) return 0;
  polling = true;
  const t0 = performance.now();
  try {
    const [domain, apiKey] = await Promise.all([deps.replyDomain(), deps.apiKey()]);
    if (!domain || !apiKey) return 0;

    const listRes = await deps.fetchFn(LIST_URL, {
      headers: { Authorization: `Bearer ${apiKey}` },
    });
    if (!listRes.ok) {
      log.warn(`[inbound] list failed: Resend ${listRes.status}`);
      return 0;
    }
    const list = (await listRes.json()) as { data?: ReceivedSummary[] };
    const state = await readState(deps.dataDir);
    const fresh = (list.data ?? []).filter((e) => e?.id && !state.seen.includes(e.id));
    if (fresh.length === 0) return 0;

    const index = await loadIndex(deps.dataDir);
    const owner = (await deps.recipient())?.toLowerCase() ?? null;
    let handled = 0;
    // Oldest first, so a thread's messages land in the order they were sent.
    for (const summary of fresh.reverse().slice(0, MAX_PER_TICK)) {
      const match = matchAssignment(index.assignments, summary.to, domain);
      if (!match) {
        log.debug(`[inbound] ignored email=${summary.id}: no assignment address`);
        await markSeen(state, summary.id, deps.dataDir);
        continue;
      }
      const id = match.assignment.id;
      const getRes = await deps.fetchFn(`${RECEIVING_URL}/${summary.id}`, {
        headers: { Authorization: `Bearer ${apiKey}` },
      });
      if (!getRes.ok) {
        // Not marked seen: the next tick retries the fetch.
        log.warn(`[inbound] retrieve failed email=${summary.id}: Resend ${getRes.status}`);
        continue;
      }
      const email = (await getRes.json()) as ReceivedEmail;
      const sender = extractAddress(email.from);
      const reject = !owner
        ? 'no owner address configured'
        : sender !== owner
          ? `sender is not the owner`
          : isAutoGenerated(email.headers)
            ? 'auto-generated mail'
            : authenticationHardFails(email.authentication)
              ? 'SPF, DKIM and DMARC all failed'
              : null;
      if (reject) {
        log.warn(`[inbound] rejected email=${summary.id} assignment=${id}: ${reject}`);
        await markSeen(state, summary.id, deps.dataDir);
        continue;
      }
      const message = replyMessageText(email);
      if (!message) {
        log.warn(`[inbound] rejected email=${summary.id} assignment=${id}: empty after stripping`);
        await markSeen(state, summary.id, deps.dataDir);
        continue;
      }

      await appendEntries(
        id,
        [
          {
            id: newId(),
            at: deps.now().toISOString(),
            kind: 'you',
            via: 'email',
            markdown: message,
          },
        ],
        deps.dataDir
      );
      await markSeen(state, summary.id, deps.dataDir);
      handled += 1;
      log.info(
        `[inbound] reply email=${summary.id} assignment=${id} chars=${message.length} to=${match.address.slice(0, 10)}…`
      );
      // Same rule as the UI route: a queued run will read every new message, so one is enough.
      if (!match.assignment.pendingRun && !match.assignment.running) {
        void deps.requestRun(id, 'message').catch((err: Error) => {
          log.error(`[inbound] reply run failed to start assignment=${id}: ${err.message}`);
        });
      }
    }
    if (handled > 0) {
      log.info(
        `[inbound] handled ${handled}/${fresh.length} new in ${(performance.now() - t0).toFixed(0)}ms`
      );
    }
    return handled;
  } catch (err) {
    log.error(`[inbound] poll failed: ${(err as Error).message}`);
    return 0;
  } finally {
    polling = false;
  }
}

/** Started from index.ts at boot. Config is read each tick, so turning the setting on just works. */
export function startInboundEmailPoller(deps: InboundDeps = defaultInboundDeps()): () => void {
  const timer = setInterval(() => void pollInboundEmails(deps), TICK_MS);
  log.info(`[boot] inbound email poller every ${TICK_MS / 1000}s`);
  return () => clearInterval(timer);
}
